// node dmwalk.js <live|nolive> <url>
const { chromium } = require('playwright');
const live = process.argv[2] !== 'nolive', url = process.argv[3] || 'http://127.0.0.1:8787/';
const out = __dirname + '/shots-dm' + (live ? '' : '-preview') + '/'; require('fs').mkdirSync(out, { recursive: true });
(async () => {
  const b = await chromium.launch({ proxy: { server: process.env.HTTPS_PROXY, bypass: '127.0.0.1,localhost' } });
  const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const errs = [];
  p.on('console', (m) => { if (m.type() === 'error' && !/404/.test(m.text())) errs.push(m.text().slice(0, 200)); });
  p.on('pageerror', (e) => errs.push('PAGEERROR ' + e.message.slice(0, 300)));
  let n = 0; const shot = async (name) => { n++; await p.waitForTimeout(700); await p.screenshot({ path: out + String(n).padStart(2, '0') + '-' + name + '.png' }); };
  const out1 = async (label) => { await p.click('.outs .btn >> text=' + label); await p.waitForTimeout(500); };
  const outFirst = async () => { await p.click('.outs .btn >> nth=0'); await p.waitForTimeout(500); };
  const aiDone = () => p.waitForFunction(() => !document.querySelector('.ai-wait'), null, { timeout: 60000 });
  await p.goto(url); await p.waitForTimeout(2200);
  await shot('title');
  await p.click('#b-dm'); await shot('gate');
  await p.click((await p.isVisible('#b-dm-skip')) ? '#b-dm-skip' : '#b-dm-in'); await shot('cover');
  await p.click('.outs .btn'); await shot('ch1-box');
  await outFirst(); await shot('ch1-snowbank');
  await outFirst(); await shot('ch1-square');
  await p.click('.try summary >> nth=0'); await shot('ch1-square-try');
  // AI: they try something off-script
  await p.fill('#dm-input', 'The reindeer in the party tries to jump onto the cart and ride it like a sled, steering with their antlers');
  await p.press('#dm-input', 'Enter'); await aiDone(); await shot('ai-try');
  console.log('AI try:', (await p.textContent('.ai >> nth=-1')).slice(0, 520));
  await p.click('.ai-res .btn >> nth=0'); await p.waitForTimeout(300);
  await out1('The choir is safe'); await shot('ch1-crumb');
  await p.click('.chipd >> text=Agent Crumb says'); await p.fill('#dm-input', 'why the troll scares him'); await p.press('#dm-input', 'Enter'); await aiDone(); await shot('ai-say');
  console.log('AI say:', (await p.textContent('.ai >> nth=-1')).slice(0, 400));
  await outFirst(); await shot('hub');
  await p.click('.errand >> text=The Coal'); await shot('coal-office');
  await out1('they read Fizzwick'); await shot('coal-cellar');
  await out1('Truly forgiven'); await shot('coal-stamp');
  await out1('They forgave Checker Twice'); await shot('bridge1');
  await out1('scarf'); await shot('hub2');
  await p.click('.errand >> text=The Laugh'); await shot('laugh-nook');
  await outFirst(); await shot('laugh-joke');
  await p.click('.chipd >> text=A twist'); await aiDone(); await shot('ai-twist');
  console.log('AI twist:', (await p.textContent('.ai >> nth=-1')).slice(0, 400));
  await out1('He laughs'); await shot('laugh-chase');
  await out1('The whole laugh'); await shot('bridge2');
  await out1('Dot told them'); await p.click('.errand >> text=The Snowflake'); await shot('snow-school');
  await outFirst(); await out1('Dame Thunderhoof flew'); await shot('snow-aurora');
  await out1('A perfect snowflake'); await shot('finale-doors');
  await p.click('.chipd >> text=Recap so far'); await aiDone(); await shot('ai-recap');
  console.log('AI recap:', (await p.textContent('.ai >> nth=-1')).slice(0, 500));
  await outFirst(); await shot('finale-machine');
  await out1('won the machine over'); await shot('finale-bake');
  await outFirst(); await shot('finale-fizz');
  await out1('They forgave him'); await shot('midnight');
  console.log('ending kind buttons:', await p.$$eval('.endpick button', (bs) => bs.map((x) => x.textContent + (x.classList.contains('on') ? '*' : '')).join(' ')));
  await outFirst(); await shot('end');
  // other tabs
  await p.click('.dmtab >> text=Story'); await shot('tab-story');
  await p.click('.dmtab >> text=Dictionary'); await shot('tab-dictionary');
  await p.fill('#lk-q', 'troll'); await shot('dictionary-search');
  await p.click('.lk >> nth=0'); await shot('sheet-grumbleknot');
  await p.click('#dm-sheet-x'); await p.click('.dmtab >> text=Party'); await p.click('text=Add a player'); await p.fill('#pt-who-0', 'Sam'); await p.fill('#pt-name-0', 'Bolt Starhoof'); await p.selectOption('#pt-race-0', 'Reindeer'); await p.selectOption('#pt-cls-0', 'Sleigh Pilot'); await shot('tab-party');
  const st = await p.evaluate(() => { const d = FR.dm.state(); return { flags: d.flags, order: d.order, feed: d.feed.length }; });
  console.log(JSON.stringify(st)); console.log('errors:', errs);
  await b.close();
})().catch((e) => { console.log('FAILED', e.message.slice(0, 500)); process.exit(1); });
